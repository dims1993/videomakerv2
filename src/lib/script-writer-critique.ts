export type ScriptWriterRevisionDecision =
  | "pass"
  | "polish"
  | "rewrite"
  | "regenerate";

export function normalizeScriptWriterRevisionDecision(
  value: unknown,
): ScriptWriterRevisionDecision | null {
  if (typeof value !== "string") {
    return null;
  }
  const normalized = value.trim().toLowerCase();
  if (
    normalized === "pass" ||
    normalized === "polish" ||
    normalized === "rewrite" ||
    normalized === "regenerate"
  ) {
    return normalized;
  }
  return null;
}

/**
 * Prefer the scorer's `decision`. Fall back to score bands when missing.
 * Ignore an inconsistent `pass` when the numeric score is still ≤ threshold.
 */
export function resolveScriptWriterRevisionDecision({
  decision,
  score,
  channelKey,
}: {
  decision?: unknown;
  score: number | null;
  channelKey?: string | null;
}): ScriptWriterRevisionDecision {
  const fromField = normalizeScriptWriterRevisionDecision(decision);
  if (fromField) {
    if (
      fromField === "pass" &&
      shouldRequestScriptRevision(score, channelKey)
    ) {
      // Scorer said pass but score is still ≤ threshold — use bands instead.
    } else {
      return fromField;
    }
  }

  if (channelKey === "wealth-insights") {
    if (score == null || !Number.isFinite(score)) {
      return "regenerate";
    }
    const passScore = getScriptWriterPassScore(channelKey);
    // Pass requires strictly above SCRIPT_WRITER_PASS_SCORE (9.2).
    if (score > passScore) {
      return "pass";
    }
    if (score >= 8.0) {
      return "polish";
    }
    if (score >= 7.0) {
      return "rewrite";
    }
    return "regenerate";
  }

  if (!shouldRequestScriptRevision(score, channelKey)) {
    return "pass";
  }
  return "rewrite";
}

/** Minimum score gain that resets the stalled-polish counter. */
export const SCRIPT_WRITER_POLISH_GAIN_MIN = 0.3;

/**
 * After two consecutive polish outcomes without enough score gain, escalate
 * to rewrite so the loop does not burn drafts on tiny edits.
 */
export function escalateStalledPolishDecision({
  decision,
  score,
  previousScore,
  stalledPolishCount,
  stallLimit = 2,
  minGain = SCRIPT_WRITER_POLISH_GAIN_MIN,
}: {
  decision: ScriptWriterRevisionDecision;
  score: number | null;
  previousScore: number | null;
  stalledPolishCount: number;
  stallLimit?: number;
  minGain?: number;
}): {
  decision: ScriptWriterRevisionDecision;
  stalledPolishCount: number;
  escalated: boolean;
} {
  if (decision !== "polish") {
    return { decision, stalledPolishCount: 0, escalated: false };
  }

  let nextStalled = stalledPolishCount;
  if (
    previousScore != null &&
    score != null &&
    Number.isFinite(previousScore) &&
    Number.isFinite(score)
  ) {
    const gain = score - previousScore;
    nextStalled = gain >= minGain ? 0 : stalledPolishCount + 1;
  }

  if (nextStalled >= stallLimit) {
    return {
      decision: "rewrite",
      stalledPolishCount: nextStalled,
      escalated: true,
    };
  }

  return {
    decision: "polish",
    stalledPolishCount: nextStalled,
    escalated: false,
  };
}

export function shouldReviseScriptForDecision(
  decision: ScriptWriterRevisionDecision,
) {
  return (
    decision === "polish" ||
    decision === "rewrite" ||
    decision === "regenerate"
  );
}

export type ScriptWriterBestDraft = {
  draftNumber: number;
  script: string;
  score: number;
  briefReason: string | null;
  mustFix: string[];
  rewritePriority: string[];
  dimensionScores: Record<string, number> | null;
};

/**
 * Keep the highest-scoring draft. Ties keep the earlier draft (stability).
 * A lower score is a regression and must not replace the best draft.
 */
export function considerScriptWriterBestDraft(
  best: ScriptWriterBestDraft | null,
  candidate: {
    draftNumber: number;
    script: string;
    score: number | null;
    briefReason: string | null;
    mustFix?: string[] | null;
    rewritePriority?: string[] | null;
    dimensionScores?: Record<string, number> | null;
  },
): {
  best: ScriptWriterBestDraft | null;
  accepted: boolean;
  rejectedAsRegression: boolean;
} {
  const script = candidate.script.trim();
  const score = candidate.score;
  if (!script || score == null || !Number.isFinite(score)) {
    return { best, accepted: false, rejectedAsRegression: false };
  }

  const next: ScriptWriterBestDraft = {
    draftNumber: candidate.draftNumber,
    script,
    score,
    briefReason: candidate.briefReason,
    mustFix: candidate.mustFix?.filter(Boolean) ?? [],
    rewritePriority: candidate.rewritePriority?.filter(Boolean) ?? [],
    dimensionScores: candidate.dimensionScores ?? null,
  };

  if (!best) {
    return {
      best: next,
      accepted: true,
      rejectedAsRegression: false,
    };
  }

  if (score > best.score) {
    return {
      best: next,
      accepted: true,
      rejectedAsRegression: false,
    };
  }

  // Equal score: keep earlier best. Lower score: reject regression.
  if (score === best.score) {
    return { best, accepted: true, rejectedAsRegression: false };
  }

  return { best, accepted: false, rejectedAsRegression: true };
}

