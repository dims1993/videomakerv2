export function buildWealthPolishDepthRules(
  decision: ScriptWriterRevisionDecision | null | undefined,
) {
  if (decision === "polish") {
    return [
      "## Polish depth lock (mandatory for decision=polish)",
      "",
      "This is a surgical polish, not a rewrite.",
      "- Change ONLY what mustFix / rewritePriority require.",
      "- Preserve strong lines, scenes, metaphors, transitions, and pacing that already work.",
      "- Do NOT restructure the whole script.",
      "- Do NOT apply broad anti-repetition cuts unless mustFix explicitly requires them.",
      "- Do NOT delay/rebuild the thesis unless mustFix explicitly requires it.",
      "- Do NOT merge paragraphs unless mustFix explicitly requires it.",
      "- If unsure whether a change helps, keep the previous wording.",
      "- The revised draft must not be weaker overall than the previous script.",
    ].join("\n");
  }

  if (decision === "rewrite" || decision === "regenerate") {
    return [
      "## Structural revision checklist (decision=" + decision + ")",
      "",
      "- Anti-repetition: state the central mechanism once clearly, then advance with new facts, decisions, consequences, examples, or revelations.",
      "- Delay the full thesis when the opening currently spoils the chain too early.",
      "- Title payoff: if the workingTitle uses a vs / comparison frame, include concrete comparison beats.",
      "- Escalation: when costs or consequences stack, show clear progression.",
      "- Merge paragraphs that perform the same narrative function.",
      "- Still preserve strong material that does not contribute to scored weaknesses.",
      "- The revised draft should improve the scored weaknesses without discarding what already works.",
    ].join("\n");
  }

  return null;
}

