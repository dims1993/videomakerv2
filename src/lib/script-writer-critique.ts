export type ScriptScoreResult = {
  score: number | null;
  decision: ScriptWriterRevisionDecision | null;
  briefReason: string | null;
  dimensionScores: Record<string, number> | null;
  strengths: string[];
  mustFix: string[];
  rewritePriority: string[];
  rawText: string;
};

/**
 * Pull a complete {"score": …} object out of assistant text when present.
 */
export function extractEmbeddedScoreJson(text: string): string | null {
  const cleaned = stripChatGptUiChrome(text.trim());
  if (!cleaned || !/"score"\s*:/i.test(cleaned)) {
    return null;
  }

  const scoreObject = extractScoreJsonObject(cleaned);
  if (scoreObject) {
    return scoreObject;
  }

  const jsonText = extractJsonPayload(cleaned);
  if (!jsonText || !/"score"\s*:/i.test(jsonText)) {
    return null;
  }

  try {
    const parsed = JSON.parse(jsonText) as { score?: unknown };
    if (normalizeScore(parsed.score) == null) {
      return null;
    }
    return jsonText;
  } catch {
    return null;
  }
}

/**
 * True when assistant text looks like a finished critique/score reply
 * (used by ChatGPT waitForCompletion for short responses).
 */
export function looksLikeScriptScoreResponse(text: string): boolean {
  const cleaned = stripChatGptUiChrome(text.trim());
  if (!cleaned) {
    return false;
  }

  if (extractEmbeddedScoreJson(cleaned)) {
    return true;
  }

  if (cleaned.length > 1200) {
    return false;
  }

  if (
    /(?:score|rating|nota|puntuaci[oó]n)\s*[:=]?\s*\d{1,2}(?:[.,]\d)?\s*(?:\/\s*10)?/i.test(
      cleaned,
    )
  ) {
    return true;
  }

  if (/\b\d{1,2}(?:[.,]\d)?\s*\/\s*10\b/.test(cleaned)) {
    return true;
  }

  return false;
}

function asStringList(value: unknown): string[] {
  if (!Array.isArray(value)) {
    return [];
  }
  return value
    .map((item) => (typeof item === "string" ? item.trim() : ""))
    .filter(Boolean);
}

function asDimensionScores(value: unknown): Record<string, number> | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return null;
  }
  const out: Record<string, number> = {};
  for (const [key, raw] of Object.entries(value as Record<string, unknown>)) {
    const score = normalizeScore(raw);
    if (score != null) {
      out[key] = score;
    }
  }
  return Object.keys(out).length > 0 ? out : null;
}

/**
 * Parse a ChatGPT critique reply into a numeric score (+ richer fields when present).
 */
export function extractScriptScore(rawResponse: string): ScriptScoreResult {
  const rawText = rawResponse.trim();
  const cleaned = stripChatGptUiChrome(rawText);
  if (!cleaned) {
    return {
      score: null,
      decision: null,
      briefReason: null,
      dimensionScores: null,
      strengths: [],
      mustFix: [],
      rewritePriority: [],
      rawText,
    };
  }

  const embedded = extractEmbeddedScoreJson(cleaned);
  const jsonText = embedded ?? extractJsonPayload(cleaned);
  if (jsonText) {
    try {
      const parsed = JSON.parse(jsonText) as {
        score?: unknown;
        overallScore?: unknown;
        decision?: unknown;
        briefReason?: unknown;
        reason?: unknown;
        mainWeakness?: unknown;
        mainStrength?: unknown;
        dimensionScores?: unknown;
        strengths?: unknown;
        mustFix?: unknown;
        rewritePriority?: unknown;
      };
      const score = normalizeScore(parsed.overallScore ?? parsed.score);
      const decision = normalizeScriptWriterRevisionDecision(parsed.decision);
      const briefReason =
        typeof parsed.briefReason === "string"
          ? parsed.briefReason.trim()
          : typeof parsed.reason === "string"
            ? parsed.reason.trim()
            : typeof parsed.mainWeakness === "string"
              ? parsed.mainWeakness.trim()
              : null;
      const strengths = asStringList(parsed.strengths);
      if (
        strengths.length === 0 &&
        typeof parsed.mainStrength === "string" &&
        parsed.mainStrength.trim()
      ) {
        strengths.push(parsed.mainStrength.trim());
      }
      if (score != null) {
        return {
          score,
          decision,
          briefReason: briefReason || null,
          dimensionScores: asDimensionScores(parsed.dimensionScores),
          strengths,
          mustFix: asStringList(parsed.mustFix),
          rewritePriority: asStringList(parsed.rewritePriority),
          rawText,
        };
      }
    } catch {
      // fall through to prose parsing
    }
  }

  const labeled = cleaned.match(
    /(?:score|rating|nota|puntuaci[oó]n)\s*[:=]?\s*(\d{1,2}(?:[.,]\d)?)\s*(?:\/\s*10)?/i,
  );
  if (labeled?.[1]) {
    return {
      score: normalizeScore(labeled[1].replace(",", ".")),
      decision: null,
      briefReason: extractProseReason(cleaned),
      dimensionScores: null,
      strengths: [],
      mustFix: [],
      rewritePriority: [],
      rawText,
    };
  }

  const outOfTen = cleaned.match(/\b(\d{1,2}(?:[.,]\d)?)\s*\/\s*10\b/);
  if (outOfTen?.[1]) {
    return {
      score: normalizeScore(outOfTen[1].replace(",", ".")),
      decision: null,
      briefReason: extractProseReason(cleaned),
      dimensionScores: null,
      strengths: [],
      mustFix: [],
      rewritePriority: [],
      rawText,
    };
  }

  const loneNumber = cleaned.match(
    /^[\s"'`]*(\d{1,2}(?:[.,]\d)?)[\s"'`*(/]*10?[\s)"'`]*$/,
  );
  if (loneNumber?.[1]) {
    return {
      score: normalizeScore(loneNumber[1].replace(",", ".")),
      decision: null,
      briefReason: null,
      dimensionScores: null,
      strengths: [],
      mustFix: [],
      rewritePriority: [],
      rawText,
    };
  }

  return {
    score: null,
    decision: null,
    briefReason: null,
    dimensionScores: null,
    strengths: [],
    mustFix: [],
    rewritePriority: [],
    rawText,
  };
}

function extractProseReason(cleaned: string): string | null {
  const afterDash = cleaned.match(
    /(?:score|rating|nota|puntuaci[oó]n)[^\n]{0,40}(?:—|-|:)\s*(.+)$/i,
  );
  const reason = afterDash?.[1]?.trim();
  if (!reason || reason.length < 8 || reason.length > 280) {
    return null;
  }
  return reason.replace(/^["'`]+|["'`]+$/g, "").trim() || null;
}

/** True when we should request another improved draft. */
export function shouldRequestScriptRevision(
  score: number | null,
  channelKey?: string | null,
) {
  if (score == null || !Number.isFinite(score)) {
    return true;
  }
  return score <= getScriptWriterPassScore(channelKey);
}

/** @deprecated Use shouldRequestScriptRevision */
export const shouldRequestScriptV2 = shouldRequestScriptRevision;

function normalizeScore(value: unknown): number | null {
  const numeric =
    typeof value === "number"
      ? value
      : typeof value === "string"
        ? Number(value.trim().replace(",", "."))
        : NaN;

  if (!Number.isFinite(numeric)) {
    return null;
  }

  if (numeric < 0 || numeric > 10) {
    return null;
  }

  return Math.round(numeric * 10) / 10;
}
