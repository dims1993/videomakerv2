const markdownPromptCache = new Map<string, string>();

async function readOptionalPromptMarkdown(relativePath: string | undefined) {
  const trimmed = relativePath?.trim();
  if (!trimmed) {
    return null;
  }

  const cached = markdownPromptCache.get(trimmed);
  if (cached != null) {
    return cached;
  }

  try {
    const text = await readProjectText(trimmed);
    markdownPromptCache.set(trimmed, text);
    return text;
  } catch {
    return null;
  }
}

